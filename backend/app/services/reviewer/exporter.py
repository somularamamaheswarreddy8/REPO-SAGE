import json
from typing import Dict, Any, List
from app.models.review import PRReview
from app.models.repository import Repository


def export_as_markdown(review: PRReview, repository: Repository) -> str:
    """Generates a clean, readable Markdown report of pull request review findings."""
    md = []
    md.append(f"# RepoSage Code Review Report: {repository.full_name} #PR{review.pr_number}")
    md.append(f"**Title:** {review.title}")
    md.append(f"**Commit Base/Head:** `{review.base_commit_sha[:8]}` → `{review.head_commit_sha[:8]}`")
    md.append(f"**Date:** {review.created_at.strftime('%Y-%m-%d %H:%M:%S UTC')}")
    md.append(f"**Review Status:** {review.status.upper()}")
    if review.model_name:
        md.append(f"**Evaluated Model:** {review.model_name} (Prompt {review.prompt_version or 'v1.0'})")
    md.append("")
    md.append("## Executive Summary")
    md.append(review.summary or "No summary provided.")
    md.append("")

    findings = review.findings or []
    crit_count = sum(1 for f in findings if f.severity == "critical")
    high_count = sum(1 for f in findings if f.severity == "high")
    med_count = sum(1 for f in findings if f.severity == "medium")
    low_count = sum(1 for f in findings if f.severity == "low")

    md.append("## Finding Counts")
    md.append(f"- **Critical:** {crit_count}")
    md.append(f"- **High:** {high_count}")
    md.append(f"- **Medium:** {med_count}")
    md.append(f"- **Low:** {low_count}")
    md.append(f"- **Total:** {len(findings)}")
    md.append("")

    md.append("## Detailed Findings")
    if not findings:
        md.append("*No security vulnerabilities or defect findings identified in this pull request.*")
    else:
        for idx, f in enumerate(findings, 1):
            category = getattr(f, "category", "security").upper()
            md.append(f"### {idx}. [{f.severity.upper()} - {category}] {f.title}")
            md.append(f"- **Location:** `{f.file_path}` (lines {f.start_line}–{f.end_line})")
            if getattr(f, "diff_line_reference", None):
                md.append(f"- **Diff Reference:** `{f.diff_line_reference}`")
            md.append(f"- **Confidence:** {int(f.confidence * 100)}%")
            md.append(f"- **Status:** {'Confirmed Problem' if f.is_confirmed_problem else 'Potential Advisory Risk'}")
            md.append("")
            md.append(f"**Explanation:**\n{f.explanation}")
            md.append("")
            md.append(f"**Why this is a problem:**\n{f.why_problem}")
            md.append("")
            md.append(f"**Suggested Improvement:**\n```\n{f.suggested_improvement}\n```")
            if f.suggested_tests:
                md.append("")
                md.append(f"**Suggested Test Cases:**\n{f.suggested_tests}")
            md.append("")
            md.append("---")
            md.append("")

    md.append("\n*Generated by RepoSage — Zero-Leakage & Evidence-Grounded Code Review Engine.*")
    return "\n".join(md)


def export_as_json(review: PRReview, repository: Repository) -> Dict[str, Any]:
    """Serializes review results into a structured machine-readable JSON dictionary."""
    findings_list = []
    for f in review.findings or []:
        findings_list.append({
            "id": f.id,
            "severity": f.severity,
            "category": getattr(f, "category", "security"),
            "title": f.title,
            "file_path": f.file_path,
            "start_line": f.start_line,
            "end_line": f.end_line,
            "diff_line_reference": getattr(f, "diff_line_reference", None),
            "explanation": f.explanation,
            "why_problem": f.why_problem,
            "suggested_improvement": f.suggested_improvement,
            "suggested_tests": f.suggested_tests,
            "confidence": f.confidence,
            "is_confirmed_problem": f.is_confirmed_problem,
            "published_to_github": f.published_to_github,
            "published_at": f.published_at.isoformat() if f.published_at else None
        })

    return {
        "repository": repository.full_name,
        "pr_number": review.pr_number,
        "title": review.title,
        "base_commit_sha": review.base_commit_sha,
        "head_commit_sha": review.head_commit_sha,
        "model_name": getattr(review, "model_name", None),
        "prompt_version": getattr(review, "prompt_version", "v1.0"),
        "status": review.status,
        "summary": review.summary,
        "created_at": review.created_at.isoformat(),
        "findings_count": len(findings_list),
        "findings": findings_list
    }


def export_as_sarif(review: PRReview, repository: Repository) -> Dict[str, Any]:
    """
    Exports review findings into standard OASIS SARIF v2.1.0 format
    compatible with GitHub Code Scanning, SonarQube, and CI/CD security pipelines.
    """
    sarif_severity_map = {
        "critical": "error",
        "high": "error",
        "medium": "warning",
        "low": "note"
    }

    rules_dict = {}
    results_list = []

    for f in review.findings or []:
        rule_id = f"RSG-{f.severity[:3].upper()}-{abs(hash(f.title)) % 10000:04d}"
        if rule_id not in rules_dict:
            rules_dict[rule_id] = {
                "id": rule_id,
                "name": f.title[:64],
                "shortDescription": {"text": f.title},
                "fullDescription": {"text": f.explanation},
                "defaultConfiguration": {
                    "level": sarif_severity_map.get(f.severity.lower(), "warning")
                },
                "properties": {
                    "tags": ["security", f.severity.lower(), getattr(f, "category", "code-quality")]
                }
            }

        result_item = {
            "ruleId": rule_id,
            "level": sarif_severity_map.get(f.severity.lower(), "warning"),
            "message": {
                "text": f"{f.title}\n\nWhy: {f.why_problem}\nFix: {f.suggested_improvement}"
            },
            "locations": [
                {
                    "physicalLocation": {
                        "artifactLocation": {
                            "uri": f.file_path,
                            "uriBaseId": "%SRCROOT%"
                        },
                        "region": {
                            "startLine": max(1, f.start_line),
                            "endLine": max(1, f.end_line)
                        }
                    }
                }
            ]
        }
        results_list.append(result_item)

    return {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "RepoSage AI Code Reviewer",
                        "version": "0.1.0",
                        "informationUri": "https://github.com/reposage/reposage",
                        "rules": list(rules_dict.values())
                    }
                },
                "results": results_list
            }
        ]
    }
